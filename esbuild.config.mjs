import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync, mkdirSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Local test vault (gitignored). If it exists, every successful build is copied into it, so Obsidian
// loads the new version (with the Hot Reload plugin even without a restart). Without the folder nothing happens.
const DEV_VAULT_PLUGIN_DIR = 'dev-vault/.obsidian/plugins/nextcloud-collectives';
const RELEASE_FILES = ['main.js', 'manifest.json', 'styles.css'];

const copyToDevVault = {
	name: 'copy-to-dev-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0 || !existsSync('dev-vault')) return;
			mkdirSync(DEV_VAULT_PLUGIN_DIR, { recursive: true });
			for (const file of RELEASE_FILES) copyFileSync(file, `${DEV_VAULT_PLUGIN_DIR}/${file}`);
			console.log(`[dev-vault] ${RELEASE_FILES.join(', ')} → ${DEV_VAULT_PLUGIN_DIR}`);
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian', 'electron',
		'@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands', '@codemirror/language',
		'@codemirror/lint', '@codemirror/search', '@codemirror/state', '@codemirror/view',
		'@lezer/common', '@lezer/highlight', '@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [copyToDevVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
