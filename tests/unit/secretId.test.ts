import { describe, expect, it } from 'vitest';
import { SECRET_ID_PREFIX, buildSecretId, isOwnSecretId, isValidSecretId } from '../../src/settings/secretId';

describe('buildSecretId', () => {
	it('builds the prefix followed by zero-padded lowercase hex of each byte', () => {
		const id = buildSecretId(new Uint8Array([0, 15, 255, 16]));

		expect(id).toBe('nextcloud-collectives-000fff10');
	});

	it('throws for an empty byte array instead of returning a bare prefix', () => {
		expect(() => buildSecretId(new Uint8Array([]))).toThrow();
	});

	it('builds a valid ID with 16 hex characters after the prefix from 8 random bytes', () => {
		const id = buildSecretId(crypto.getRandomValues(new Uint8Array(8)));

		expect(id).toHaveLength(SECRET_ID_PREFIX.length + 16);
		expect(isValidSecretId(id)).toBe(true);
	});
});

describe('isValidSecretId', () => {
	it.each([
		['abc-123'],
		['nextcloud-collectives-00ff'],
	])('accepts "%s"', (id) => {
		expect(isValidSecretId(id)).toBe(true);
	});

	it.each([
		['empty string', ''],
		['uppercase letters', 'ABC'],
		['underscore', 'a_b'],
		['space', 'a b'],
		['non-ASCII letter', 'ä'],
		['slash', 'a/b'],
	])('rejects %s (%s)', (_label, id) => {
		expect(isValidSecretId(id)).toBe(false);
	});
});

describe('isOwnSecretId', () => {
	it('accepts the prefix followed by lowercase hex', () => {
		expect(isOwnSecretId('nextcloud-collectives-0f')).toBe(true);
	});

	it('accepts an ID generated by buildSecretId', () => {
		const id = buildSecretId(crypto.getRandomValues(new Uint8Array(8)));

		expect(isOwnSecretId(id)).toBe(true);
	});

	it.each([
		['empty string', ''],
		['bare prefix without hex', 'nextcloud-collectives-'],
		['uppercase hex', 'nextcloud-collectives-0F'],
		['non-hex letters after the prefix', 'nextcloud-collectives-xyz'],
		['extra suffix after the hex', 'nextcloud-collectives-0f-extra'],
		['foreign ID without prefix', 'my-old-id'],
		['other plugin token', 'other-plugin-token'],
		['leading space before the prefix', ' nextcloud-collectives-0f'],
		['prefix glued to another word', 'xnextcloud-collectives-0f'],
	])('rejects %s (%j)', (_label, id) => {
		expect(isOwnSecretId(id)).toBe(false);
	});
});
